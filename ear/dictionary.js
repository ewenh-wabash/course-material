function showDefinition(word, definition, x, y) {
  let popup = document.getElementById("dictPopup");
  if (!popup) {
    popup = document.createElement("div");
    popup.id = "dictPopup";
    popup.style.position = "absolute";
    popup.style.background = "white";
    popup.style.border = "1px solid #ccc";
    popup.style.padding = "10px";
    popup.style.borderRadius = "6px";
    popup.style.boxShadow = "0 2px 10px rgba(0,0,0,0.2)";
    popup.style.zIndex = "9999";
    document.body.appendChild(popup);
  }

  popup.innerHTML = `<strong>${word}</strong><br>${definition}`;
  popup.style.left = x + "px";
  popup.style.top = y + "px";
  popup.style.display = "block";
}

document.addEventListener("click", () => {
  const popup = document.getElementById("dictPopup");
  if (popup) popup.style.display = "none";
});



function handleLookup(e) {
  e.preventDefault();


  // Check if the clicked element (or its parent) has a meaning
  let el = e.target;
  while (el && !el.dataset.meaning) {
    el = el.parentElement;
  }

  if (el && el.dataset.meaning) {
    const key = el.dataset.meaning;
    if (dictionary[key]) {
      showDefinition(key, dictionary[key], e.pageX, e.pageY);
      return;
    }
  }

  // otherwise continue to analyse

  let range, textNode, offset;
  if (document.caretRangeFromPoint) {
    range = document.caretRangeFromPoint(e.clientX, e.clientY);
    textNode = range.startContainer;
    offset = range.startOffset;
  } else if (document.caretPositionFromPoint) {
    const pos = document.caretPositionFromPoint(e.clientX, e.clientY);
    textNode = pos.offsetNode;
    offset = pos.offset;
  }

  if (!textNode || textNode.nodeType !== Node.TEXT_NODE) {
    return;
  }

  let fullText = textNode.textContent;

  // Expand to full word under caret
  let start = offset, end = offset;
  while (start > 0 && !/\s/.test(fullText[start - 1])) start--;
  while (end < fullText.length && !/\s/.test(fullText[end])) end++;

  let wordUnderCaret = fullText.slice(start, end);

  const normalize = str => str.replace(/[^\w\s]/g, "").toLowerCase();
  wordUnderCaret = normalize(wordUnderCaret);

  const leftText = fullText.slice(0, start).trim();
  const rightText = fullText.slice(end).trim();

  const leftWords = leftText.split(/\s+/).filter(Boolean).map(normalize);
  const rightWords = rightText.split(/\s+/).filter(Boolean).map(normalize);


  const maxPhraseWords = 3;

  for (let totalWords = maxPhraseWords; totalWords >= 1; totalWords--) {

    for (let leftCount = Math.min(leftWords.length, totalWords - 1); leftCount >= 0; leftCount--) {
      const rightCount = totalWords - 1 - leftCount;
      if (rightCount > rightWords.length) continue;

      const candidateWords = [
        ...leftWords.slice(leftWords.length - leftCount),
        wordUnderCaret,
        ...rightWords.slice(0, rightCount)
      ];

      const candidate = candidateWords.join(" ");
      console.log("testing", candidate)

      if (dictionary[candidate]) {
        showDefinition(candidate, dictionary[candidate], e.pageX, e.pageY);
        return;
      }

      // if (totalWords === 1) {
      const pluralsToTry = [];

      if (candidate.endsWith("ies")) {
        pluralsToTry.push(candidate.slice(0, -3) + "y"); // puppies → puppy
      }
      if (candidate.endsWith("es")) {
        pluralsToTry.push(candidate.slice(0, -2)); // buses → bus
      }
      if (candidate.endsWith("s")) {
        pluralsToTry.push(candidate.slice(0, -1)); // cats → cat
      }
      if (candidate.endsWith("ing")) {
        pluralsToTry.push(candidate.slice(0, -3)); // hearing -> hear
      }

      for (const singularCandidate of pluralsToTry) {
        if (dictionary[singularCandidate]) {
          showDefinition(singularCandidate, dictionary[singularCandidate], e.pageX, e.pageY);
          return;
        }
      }
      // }
    }
  }

}


document.addEventListener("contextmenu", handleLookup);
document.addEventListener("dblclick", handleLookup);

